// ==========================================================
// 1번 문제: 암묵적 타입 변환 (문자열 연결)
// ==========================================================
// Q. 아래 코드를 실행하면 어떤 타입의 어떤 값이 출력될까요?
let q1 = '10' + 5 + true;
console.log(`1번 결과: ${q1}`); // 105true
console.log(`1번 타입: ${typeof q1}`); // string


// ==========================================================
// 2번 문제: 암묵적 타입 변환 (숫자 변환 및 Falsy)
// ==========================================================
// Q. 뺄셈 연산으로 인해 암묵적 숫자 변환이 일어납니다. q2의 값과 타입은 무엇일까요?
let q2 = 10 - '2' - null;
console.log(`2번 결과: ${q2}`); // 8
console.log(`2번 타입: ${typeof q2}`); // number


// ==========================================================
// 3번 문제: 암묵적 타입 변환 (단항 연산자 및 Falsy)
// ==========================================================
// Q. 단항 덧셈 연산자(+)는 숫자 변환을 시도합니다. q3의 값과 타입은 무엇일까요?
//    (힌트: true는 1, 빈 문자열('')은 0, 'false'는 Truthy입니다.)
let q3 = (+true) + (+'') + (+'false');
console.log(`3번 결과: ${q3}`); // 
console.log(`3번 타입: ${typeof q3}`); //


// ==========================================================
// 4번 문제: 명시적 타입 변환 (parseInt)
// ==========================================================
// Q. parseInt 함수는 문자열을 분석하여 정수로 변환합니다. q4의 값은 무엇일까요?
//    (힌트: 변환 가능한 부분까지만 변환하고 나머지는 버려집니다.)
let q4 = parseInt('15.5cm');
console.log(`4번 결과: ${q4}`); // 15.5
console.log(`4번 타입: ${typeof q4}`); // number


// ==========================================================
// 5번 문제: 명시적 타입 변환 (Boolean 생성자 함수)
// ==========================================================
// Q. Boolean() 함수를 사용하여 불리언 타입으로 변환합니다. q5의 값은 무엇일까요?
//    (힌트: Falsy 6가지 값을 기억하세요. 빈 객체({})는 Falsy가 아닙니다.)
let q5 = Boolean(0) || Boolean({});
console.log(`5번 결과: ${q5}`); // 0
console.log(`5번 타입: ${typeof q5}`); // boolean
